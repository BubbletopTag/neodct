static bool sandbox_up(void)
{
    const char *base = getenv("TMPDIR");

    if (base == NULL || base[0] == '\0')
        base = "/tmp";
    if (nd_snprintf(g_sandbox, sizeof g_sandbox, "%s/ndremote-XXXXXX", base) != ND_OK)
        return false;
    if (mkdtemp(g_sandbox) == NULL)
        return false;
    if (nd_snprintf(g_ctl, sizeof g_ctl, "%s/ctl", g_sandbox) != ND_OK ||
        nd_snprintf(g_bindir, sizeof g_bindir, "%s/bin", g_sandbox) != ND_OK)
        return false;
    if (mkdir(g_ctl, 0755) != 0 || mkdir(g_bindir, 0755) != 0)
        return false;
    if (!run("mkdir -p '%s/dl'", g_sandbox))
        return false;

    /* Every virtual path below ("/dl/UPDATE.ndsw") lands inside the
     * sandbox, so nothing this test writes can reach a real /NeoDCT. */
    return nd_path_set_root(g_sandbox) == ND_OK;
}

/* Put the stand-in first on PATH. Split from the copy because
 * test_no_curl_at_all() empties PATH, and everything here -- including
 * system() -- needs it back afterwards without shelling out to do it. */
static bool path_with_fake_curl(void)
{
    char path[ND_PATH_MAX * 2];

    if (nd_snprintf(path, sizeof path, "%s:%s", g_bindir, g_path_keep) != ND_OK)
        return false;
    return setenv("PATH", path, 1) == 0;
}

static bool fake_curl_install(void)
{
    const char *old = getenv("PATH");

    (void)nd_strlcpy(g_path_keep, (old != NULL) ? old : "/usr/bin:/bin", sizeof g_path_keep);
    if (!run("cp '%s' '%s/curl' && chmod 0755 '%s/curl'", fixture("fake-curl"), g_bindir, g_bindir))
        return false;
    return path_with_fake_curl() && setenv("NDCURL_DIR", g_ctl, 1) == 0;
}

