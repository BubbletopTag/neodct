/* The call log the stand-in appends to: one "<url>|<range>" per spawn. */
#define MAX_CALLS 32

static struct {
    char url[ND_REMOTE_URL_MAX];
    char range[64];
} g_calls[MAX_CALLS];
static size_t g_n_calls;

static void calls_read(void)
{
    char p[ND_PATH_MAX];
    char line[ND_REMOTE_URL_MAX + 96];
    FILE *f;

    g_n_calls = 0u;
    if (nd_snprintf(p, sizeof p, "%s/calls", g_ctl) != ND_OK)
        return;
    f = fopen(p, "r");
    if (f == NULL)
        return;
    while (g_n_calls < MAX_CALLS && fgets(line, sizeof line, f) != NULL) {
        char *bar = strchr(line, '|');
        char *nl;

        if (bar == NULL)
            continue;
        *bar = '\0';
        nl = strchr(bar + 1, '\n');
        if (nl != NULL)
            *nl = '\0';
        (void)nd_strlcpy(g_calls[g_n_calls].url, line, sizeof g_calls[0].url);
        (void)nd_strlcpy(g_calls[g_n_calls].range, bar + 1, sizeof g_calls[0].range);
        g_n_calls++;
    }
    (void)fclose(f);
}

/* ------------------------------------------------------------------ *
 * The sleep seam, and the progress recorder
 * ------------------------------------------------------------------ */

#define MAX_WAITS 16
static uint32_t g_waits[MAX_WAITS];
static size_t g_n_waits;

static void record_wait(void *ctx, uint32_t seconds)
{
    ND_UNUSED(ctx);
    if (g_n_waits < MAX_WAITS)
        g_waits[g_n_waits] = seconds;
    g_n_waits++;
}

/* Not an array: the number of callbacks is however many read()s the pipe
 * happens to give up, which is not a property worth pinning. What is worth
 * pinning is that it only ever goes forwards and that it arrives at the
 * whole size -- `seen == sorted(seen)` and `seen[-1] == size` in the
 * Python. */
static int64_t g_progress_last;
static int64_t g_progress_total;
static size_t g_n_progress;
static bool g_progress_went_backwards;

static void progress_reset(void)
{
    g_progress_last = 0;
    g_progress_total = -1;
    g_n_progress = 0u;
    g_progress_went_backwards = false;
}

static void record_progress(void *ctx, int64_t done, int64_t total)
{
    ND_UNUSED(ctx);
    if (done < g_progress_last)
        g_progress_went_backwards = true;
    g_progress_last = done;
    g_progress_total = total;
    g_n_progress++;
}

