/* ------------------------------------------------------------------ *
 * 2. Version ordering, against the real Python
 * ------------------------------------------------------------------ */

static void test_version_order_matches_python(void)
{
    char line[512];
    FILE *f = fopen(fixture("version_order.txt"), "r");
    size_t pairs = 0u;
    size_t disagreed = 0u;

    if (f == NULL) {
        CHECK(false, "version_order.txt is readable");
        return;
    }
    while (fgets(line, sizeof line, f) != NULL) {
        char *first;
        char *second;
        char *nl;
        bool want;
        bool got;

        if (line[0] == '#')
            continue;
        nl = strchr(line, '\n');
        if (nl != NULL)
            *nl = '\0';
        first = strchr(line, '|');
        if (first == NULL)
            continue;
        *first = '\0';
        second = strchr(first + 1, '|');
        if (second == NULL)
            continue;
        *second = '\0';

        want = (second[1] == '1');
        got = nd_remote_is_newer(line, first + 1);
        pairs++;
        if (got != want) {
            disagreed++;
            if (disagreed <= 5u)
                (void)fprintf(stderr,
                              "FAIL %s  is_newer(\"%s\", \"%s\"): C says %d, remote.py says %d\n",
                              __FILE__, line, first + 1, (int)got, (int)want);
        }
    }
    (void)fclose(f);

    CHECK(pairs > 500u, "the whole ordering oracle was read");
    CHECK_INT(disagreed, 0, "the C agrees with remote.py on every ordered pair");
    g_checks += (int)pairs; /* each pair really was an assertion */
}

static void test_version_order_spot_checks(void)
{
    nd_verkey a;
    nd_verkey b;

    /* The one that made the phone sit on 0.3.9a for ever, telling its owner
     * it was up to date. Compared as text, "0.3.9a" > "0.3.10a". */
    CHECK(nd_remote_is_newer("0.3.10a", "0.3.9a"), "0.3.10a is newer than 0.3.9a");
    CHECK(!nd_remote_is_newer("0.3.9a", "0.3.10a"), "and not the other way round");

    nd_verkey_parse("0.4.0a", &a);
    nd_verkey_parse("0.3.99a", &b);
    CHECK(nd_verkey_cmp(&a, &b) > 0, "0.4.0a sorts above 0.3.99a");

    CHECK(!nd_remote_is_newer("0.3.7a", "0.3.7a"), "the same version is not offered");
    CHECK(nd_remote_is_newer("0.3.7a", NULL), "anything is newer than nothing");
    CHECK(nd_remote_is_newer("0.3.7a", ""), "including the empty string");

    /* Python tuple ordering: a prefix is smaller than what it is a prefix
     * of, so 0.3.7 is older than 0.3.7.1. */
    nd_verkey_parse("0.3.7", &a);
    nd_verkey_parse("0.3.7.1", &b);
    CHECK(nd_verkey_cmp(&a, &b) < 0, "a prefix is the smaller key");

    /* A chunk that is not <digits><letters> sorts as (-1, chunk), below
     * every numeric chunk -- which is why a stray "v" makes a version
     * OLDER rather than newer. */
    CHECK(!nd_remote_is_newer("v0.3.7a", "0.3.7a"), "a tag that kept its v does not win");

    nd_verkey_parse("  0.3.7a  ", &a);
    nd_verkey_parse("0.3.7a", &b);
    CHECK_INT(nd_verkey_cmp(&a, &b), 0, "str.strip() -- surrounding space is not a version");
}

