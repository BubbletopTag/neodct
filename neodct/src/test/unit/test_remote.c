static char *real_of(const char *virt)
{
    static char slots[3][ND_PATH_MAX];
    static unsigned next;
    char *p = slots[next % 3u];

    next++;
    if (nd_path_resolve(p, ND_PATH_MAX, virt) != ND_OK)
        return NULL;
    return p;
}

static long size_of(const char *real)
{
    struct stat st;

    return (real != NULL && stat(real, &st) == 0) ? (long)st.st_size : -1;
}

static uint8_t *slurp(const char *real, size_t *len)
{
    FILE *f;
    long n;
    uint8_t *buf;

    *len = 0u;
    if (real == NULL)
        return NULL;
    f = fopen(real, "rb");
    if (f == NULL)
        return NULL;
    (void)fseek(f, 0, SEEK_END);
    n = ftell(f);
    (void)fseek(f, 0, SEEK_SET);
    if (n <= 0) {
        (void)fclose(f);
        return NULL;
    }
    buf = malloc((size_t)n);
    if (buf != NULL && fread(buf, 1u, (size_t)n, f) != (size_t)n) {
        free(buf);
        buf = NULL;
    }
    (void)fclose(f);
    if (buf != NULL)
        *len = (size_t)n;
    return buf;
}

/* Seed "<dest>.part" with the first `n` bytes of the package, or with `n`
 * bytes of something that is NOT the package when `wrong` is true. */
static void seed_partial(const char *dest_virt, long n, bool wrong)
{
    char virt[ND_PATH_MAX];

    if (nd_snprintf(virt, sizeof virt, "%s.part", dest_virt) != ND_OK)
        return;
    if (wrong)
        (void)run("tr '\\0' 'z' < /dev/zero | head -c %ld > '%s'", n, real_of(virt));
    else
        (void)run("head -c %ld '%s' > '%s'", n, fixture("package.bin"), real_of(virt));
}

