static void test_the_backoff(void)
{
    char why[ND_REMOTE_WHY_MAX];

    /* When the bearer drops the whole data session goes, DNS included, and
     * five immediate retries are five failures in under a second -- after
     * which the phone has given up on a connection that would have come
     * back on its own. */
    scenario_reset();
    clear_downloads();
    ctl_body("package.bin");
    ctl_set("fail_first", "99");
    g_n_waits = 0u;

    CHECK(nd_remote_download("https://example.invalid/pkg", DEST, PKG_SIZE, NULL, NULL, 4, NULL,
                             why, sizeof why) != ND_UPD_OK,
          "four failures give up");
    CHECK_INT(g_n_waits, 3, "with three waits between four attempts");
    if (g_n_waits == 3u) {
        CHECK_INT(g_waits[0], 5, "5 seconds");
        CHECK_INT(g_waits[1], 10, "then 10");
        CHECK_INT(g_waits[2], 20, "then 20 -- doubling");
    }
    CHECK(strstr(why, "Could not resolve host") != NULL,
          "and curl's own reason reaches the screen");

    /* Doubling for ever means a phone that looks hung rather than patient. */
    scenario_reset();
    ctl_body("package.bin");
    ctl_set("fail_first", "99");
    g_n_waits = 0u;
    (void)nd_remote_download("https://example.invalid/pkg", DEST, PKG_SIZE, NULL, NULL, 8, NULL,
                             why, sizeof why);
    CHECK_INT(g_n_waits, 7, "seven waits between eight attempts");
    if (g_n_waits == 7u) {
        CHECK_INT(g_waits[4], ND_REMOTE_RETRY_BACKOFF_MAX, "the fifth wait is already capped");
        CHECK_INT(g_waits[6], ND_REMOTE_RETRY_BACKOFF_MAX, "and it stays capped");
    }
}

